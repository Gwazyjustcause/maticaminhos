import assert from 'node:assert/strict';
import {parseSearch,expandStreet,portugueseFeature,matchesFeature,catalogMatches,findPlaces,parseMapsCoordinates} from './search.mjs';
const feature=(properties,coordinates=[-7.9054,40.6122])=>({type:'Feature',properties:{countrycode:'PT',...properties},geometry:{type:'Point',coordinates}});
assert.equal(expandStreet('R. Bela Vista'),'Rua Bela Vista');
let parsed=parseSearch('R. Bela Vista, São João de Lourosa');
assert.equal(parsed.term,'Rua Bela Vista');assert.equal(parsed.town,'São João de Lourosa');assert.equal(parsed.street,true);
assert.equal(parseSearch('Rua Bela Vista São João de Lourosa').town,'São João de Lourosa');
assert.equal(parseSearch('Rua da Sofia 20 Coimbra').town,'Coimbra');
assert.equal(parseSearch('Rua da Sofia 20','Coimbra').house,'20');
assert.equal(portugueseFeature(feature({name:'Paris',countrycode:'FR'})),false);
assert.equal(portugueseFeature(feature({name:'Lisboa',countrycode:'pt'})),true);
assert.equal(portugueseFeature(feature({name:'Unknown',countrycode:null})),false);
const street=feature({name:'Rua Bela Vista',osm_key:'highway',district:'São João de Lourosa',city:'Viseu'});
assert.equal(matchesFeature(street,parsed),true);
assert.equal(matchesFeature(feature({name:'Rua Principal',osm_key:'highway',district:'São João de Lourosa'}),parsed),false);
assert.equal(matchesFeature(feature({name:'Rua Bela Vista',osm_key:'highway',city:'Loures'}),parsed),false);
parsed=parseSearch('Rua das Flores','Porto');
assert.equal(matchesFeature(feature({name:'Rua das Flores',osm_key:'highway',city:'Porto Santo'}),parsed),false);
assert.equal(matchesFeature(feature({name:'Rua das Flores',osm_key:'highway',city:'Matosinhos',county:'Porto'}),parsed),false);
parsed=parseSearch('Rua da Sofia 20','Coimbra');
assert.equal(matchesFeature(feature({street:'Rua da Sofia',housenumber:'92',city:'Coimbra'}),parsed),false);
assert.equal(matchesFeature(feature({street:'Rua da Quinta da Portela',housenumber:'20',city:'Coimbra'}),parsed),false);
assert.equal(catalogMatches(parseSearch('O Casimiro'))[0].name,'Restaurante O Casimiro');
assert.equal(catalogMatches(parseSearch('O Casimiro Penacova')).length,1);
assert.equal(catalogMatches(parseSearch('O Casimiro','Porto')).length,0);
assert.equal(matchesFeature(feature({name:'Rua Professor Casimiro',osm_key:'highway'}),parseSearch('O Casimiro')),false);
const depot={lat:40.1299257,lon:-8.5240277},calls=[];
const mock=async(endpoint,params)=>{
  calls.push({endpoint,params});assert.equal(params.get('countrycode'),'PT');
  if(params.get('q')==='São João de Lourosa')return {features:[feature({name:'São João de Lourosa',osm_key:'place',osm_value:'village',city:'Viseu'})]};
  return {features:[feature({name:'Rua Bela Vista',osm_key:'highway',city:'São Paulo',countrycode:'BR'}),feature({name:'Rua Principal',osm_key:'highway',district:'São João de Lourosa',city:'Viseu'})]};
};
const found=await findPlaces('R. Bela Vista, São João de Lourosa','',depot,mock);
assert.equal(found.places.length,1);assert.equal(found.places[0].localityFallback,true);assert.equal(found.places[0].approximate,true);assert.match(found.places[0].note,/não a rua/);
assert.ok(calls.some(call=>call.params.has('bbox')));assert.ok(calls.some(call=>call.endpoint==='structured'));
const foreign=await findPlaces('Paris','',depot,async()=>({features:[feature({name:'Paris',countrycode:'FR'})]}));assert.equal(foreign.places.length,0);
const imported=parseMapsCoordinates('https://www.google.com/maps/place/Test/@40,-8,14z/data=!3d40.2637622!4d-8.2775141');assert.equal(imported.lat,40.2637622);assert.equal(imported.lon,-8.2775141);
assert.equal(parseMapsCoordinates('https://google.com.evil.test/maps/@40,-8,14z'),null);
assert.equal(parseMapsCoordinates('https://www.google.com/maps?q=40.2,-8.3').lat,40.2);
console.log('Passed: Portugal-only results, street abbreviations, town scoping, wrong-street/house rejection, verified restaurant listing, explicit locality fallback, and Google coordinate links.');
