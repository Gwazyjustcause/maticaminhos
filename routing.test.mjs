import assert from 'node:assert/strict';
import {tripLegs,legKey,routeBatches,routePayload,parseTrip,totalTrip,arrivalTime,moveStop,normalizeQuery,decodePolyline6,matrixBatches,accessKey,roadAccessPayload,resolveRoadAccess,routingLocation} from './routing.mjs';
const depot={name:'Empresa',lat:40,lon:-8},a={name:'Continente',lat:41,lon:-8},b={name:'Entrega por morada',lat:42,lon:-8};
const overrides={[legKey(a,b)]:'avoid',[legKey(b,depot)]:'avoid'};
const legs=tripLegs(depot,[a,b],true,'allow',overrides);
assert.deepEqual(legs.map(l=>l.mode),['allow','avoid','avoid']);
assert.deepEqual(tripLegs(depot,[b,a],true,'allow',overrides).map(l=>l.mode),['allow','allow','allow'],'Overrides apply to exact directed pairs, not list positions.');
assert.equal(tripLegs(depot,[a,b],false,'allow',overrides).length,2);
assert.equal(tripLegs(depot,[],true,'allow').length,0);
assert.deepEqual(routeBatches(legs).map(batch=>batch.legs.length),[1,2]);
assert.equal(routeBatches([legs[0],{...legs[2],mode:'allow'}]).length,2,'Cached gaps must not produce a disconnected route batch.');
assert.equal(routeBatches(Array.from({length:26},(_,i)=>({from:i?{lat:i,lon:0}:depot,to:{lat:i+1,lon:0},mode:'allow'}))).length,5);
const batch={mode:'avoid',legs:[legs[1]]};
assert.equal(routePayload(batch).costing_options.auto.exclude_tolls,true);
const response={trip:{status:0,legs:[{summary:{time:120,length:3,has_toll:false},shape:'??AA'}]}};
const parsed=parseTrip(response,batch);
assert.equal(parsed[0].distance,3000);assert.equal(parsed[0].duration,120);
assert.deepEqual(parsed[0].geometry.coordinates,[[0,0],[0.000001,0.000001]]);
assert.throws(()=>parseTrip({trip:{status:0,legs:[{summary:{time:120,length:3,has_toll:true},shape:'??AA'}]}},batch),/sem portagens/);
assert.throws(()=>parseTrip({trip:{status:0,legs:[{summary:{time:120,length:3},shape:'??AA'}]}},batch),/sem portagens/,'Unknown toll status must not be shown as toll-free.');
assert.throws(()=>parseTrip({trip:{status:0,legs:[]}},batch));
assert.throws(()=>decodePolyline6('_'));
assert.deepEqual(totalTrip([{duration:600,distance:5000},{duration:900,distance:10000},{duration:300,distance:2000}],2,10),{driving:1800,distance:17000,delivery:1200,duration:3000});
assert.equal(arrivalTime('23:45',1800),'00:15 (+1 dia)');
assert.equal(arrivalTime('08:30',3000),'09:20');
assert.deepEqual(moveStop([a,b],0,1),[b,a]);assert.deepEqual(moveStop([a,b],0,-1),[a,b]);
assert.equal(normalizeQuery('3150287'),'3150-287 Portugal');
assert.equal(normalizeQuery('3150 287'),'3150-287 Portugal');
assert.equal(normalizeQuery('3150-287'),'3150-287 Portugal');
assert.equal(normalizeQuery('3150'),'3150 Portugal');
assert.equal(normalizeQuery('Rua da Sofia 20, Coimbra'),'Rua da Sofia 20, Coimbra');
const chunks=matrixBatches(Array.from({length:26},(_,i)=>i));
assert.equal(chunks.length,9);assert.equal(chunks.reduce((sum,batch)=>sum+batch.sources.length*batch.targets.length,0),676);
const pairs=new Set();for(const batch of chunks){assert.ok(batch.sources.length*batch.targets.length<=100);for(const source of batch.sources)for(const target of batch.targets)pairs.add(`${source}:${target}`);}assert.equal(pairs.size,676);
console.log('Passed: mixed per-leg toll modes, return legs, reorder identity, batching/cache gaps, toll-free verification, map geometry, whole-trip time, arrival rollover, and postcodes.');
const restaurant={name:'Pin no edifício',lat:40,lon:-8};
const original=structuredClone(restaurant);
const access=resolveRoadAccess(restaurant,{edges:[{correlated_lat:40.002,correlated_lon:-8},{correlated_lat:40.001,correlated_lon:-8},{correlated_lat:NaN,correlated_lon:-8}]});
assert.equal(access.lat,40.001);assert.ok(access.offset>110&&access.offset<112);assert.deepEqual(restaurant,original);
const located={...restaurant,road:access};
assert.equal(pointKeyForTest(restaurant),pointKeyForTest(located));
function pointKeyForTest(p){return legKey(p,depot);}
assert.equal(routingLocation(located).lat,40.001);
assert.equal(routePayload({mode:'allow',legs:tripLegs(depot,[located],false,'allow')}).locations[1].lat,routingLocation(located).lat);
assert.equal(roadAccessPayload([restaurant]).costing,'auto');
assert.equal(roadAccessPayload([restaurant]).locations[0].minimum_reachability,50);
assert.equal(roadAccessPayload([restaurant]).locations[0].search_filter.exclude_ramp,true);
